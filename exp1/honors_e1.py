# Experiment 1
# To Clean, Integrate and Transform Electronic Healthcare Records

import pandas as pd
# 1. Load the datasets

patients = pd.read_csv("patients.csv")
conditions = pd.read_csv("conditions.csv")

print("Patients Dataset:")
print(patients.head())

print("\nConditions Dataset:")
print(conditions.head())

# 2. Display basic information

print("\n--- Patients Dataset Information ---")
print(patients.info())

print("\n--- Conditions Dataset Information ---")
print(conditions.info())

print("\nPatients Shape:", patients.shape)
print("Conditions Shape:", conditions.shape)


# 3. Check missing values

print("\n--- Missing Values in Patients Dataset ---")
print(patients.isnull().sum())

print("\n--- Missing Values in Conditions Dataset ---")
print(conditions.isnull().sum())


# 4. Check duplicate records

print("\nDuplicate records in Patients:", patients.duplicated().sum())
print("Duplicate records in Conditions:", conditions.duplicated().sum())


# 5. Remove duplicate records

patients = patients.drop_duplicates()
conditions = conditions.drop_duplicates()

print("\nDuplicates removed successfully.")


# 6. Convert date columns into datetime format

patient_date_columns = ["BIRTHDATE", "DEATHDATE"]

for col in patient_date_columns:
    patients[col] = pd.to_datetime(patients[col], errors="coerce")

condition_date_columns = ["START", "STOP"]

for col in condition_date_columns:
    conditions[col] = pd.to_datetime(conditions[col], errors="coerce")

print("\nDate columns converted to datetime format.")


# 7. Handle missing categorical values

categorical_columns = ["GENDER", "RACE", "ETHNICITY", "MARITAL"]

for col in categorical_columns:
    patients[col] = patients[col].fillna("Unknown")

print("\nMissing categorical values handled.")


# 8. Create patient age

reference_date = pd.Timestamp("2026-01-01")

patients["AGE"] = (
    (reference_date - patients["BIRTHDATE"]).dt.days / 365.25
).round(1)

print("\nAge column created.")
print(patients[["Id", "BIRTHDATE", "AGE"]].head())


# 9. Calculate condition duration

conditions["CONDITION_DURATION_DAYS"] = (
    conditions["STOP"] - conditions["START"]
).dt.days

print("\nCondition duration calculated.")
print(
    conditions[
        ["PATIENT", "DESCRIPTION", "START", "STOP",
         "CONDITION_DURATION_DAYS"]
    ].head()
)


# 10. Integrate Patients and Conditions datasets

merged_data = pd.merge(
    conditions,
    patients,
    left_on="PATIENT",
    right_on="Id",
    how="left"
)

print("\n--- Integrated Dataset ---")
print(merged_data.head())

print("\nIntegrated Dataset Shape:", merged_data.shape)


# 11. Select useful attributes

final_data = merged_data[
    [
        "PATIENT",
        "DESCRIPTION",
        "START",
        "STOP",
        "CONDITION_DURATION_DAYS",
        "GENDER",
        "RACE",
        "ETHNICITY",
        "MARITAL",
        "CITY",
        "STATE",
        "AGE",
        "HEALTHCARE_EXPENSES",
        "HEALTHCARE_COVERAGE"
    ]
]

print("\n--- Final Processed Dataset ---")
print(final_data.head())


# 12. Check the cleaned dataset

print("\nMissing values in final dataset:")
print(final_data.isnull().sum())


# 13. Save the processed dataset

final_data.to_csv("processed_healthcare_data.csv", index=False)

print("\nProcessed healthcare data saved as:")
print("processed_healthcare_data.csv")